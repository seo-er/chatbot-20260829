if "messages" not in st.session_state:

    st.session_state.messages = [
        {
            "role": "assistant",
            "content": """
# 👋 안녕하세요!

저는 **창업 시작 봇 🚀**입니다.

아직 아이디어가 없어도 괜찮아요.

막연한 생각을 이야기해주시면

**아이디어 → 고객 → 문제 → 시장 → 수익모델 → MVP → 검증 → 실행계획**

순서로 함께 구체화해드릴게요.

### 💡 이렇게 시작해보세요

**1. 아이디어가 있다면**
> 반려동물을 위한 이동 서비스를 만들고 싶어요.

**2. 불편한 점만 있다면**
> 병원에 가야 하는데 부모님이 혼자 가기 힘들어하는 경우가 많아요.

**3. 아이디어가 없다면**
> 창업하고 싶은데 뭘 해야 할지 모르겠어요.

### 🚀 가장 중요한 것

완성된 사업 아이디어가 아니어도 됩니다.

**생각나는 대로 편하게 이야기해주세요.**
제가 질문을 통해 사업 아이디어로 발전시켜드릴게요.
"""
        }
    ]

# ==================================================
# 대화 초기화
# ==================================================

if st.sidebar.button("🗑️ 상담 내용 초기화"):

    st.session_state.messages = [
        {
            "role": "assistant",
            "content": """
안녕하세요! 👋

새로운 창업 상담을 시작해볼까요?

아이디어가 있다면 편하게 이야기해주세요. 🚀
"""
        }
    ]

    st.rerun()

# ==================================================
# 기존 메시지 출력
# ==================================================

for message in st.session_state.messages:

    with st.chat_message(message["role"]):

        st.markdown(message["content"])

# ==================================================
# 사용자 질문
# ==================================================

prompt = st.chat_input(
    "창업 아이디어나 고민을 입력해주세요..."
)

if prompt:

    # 사용자 메시지 저장
    st.session_state.messages.append(
        {
            "role": "user",
            "content": prompt
        }
    )

    # 사용자 메시지 표시
    with st.chat_message("user"):

        st.markdown(prompt)

    # ==================================================
    # 최근 대화만 API에 전달
    # ==================================================

    conversation = st.session_state.messages[-20:]

    # ==================================================
    # OpenAI API
    # ==================================================

    stream = client.responses.create(

        # 현재 사용 가능한 모델명으로 변경
        model="gpt-5.6",

        instructions=SYSTEM_PROMPT,

        input=[
            {
                "role": message["role"],
                "content": message["content"]
            }
            for message in conversation
        ],

        stream=True
    )

    # ==================================================
    # Streaming Generator
    # ==================================================

    def response_generator():

        for event in stream:

            if event.type == "response.output_text.delta":

                yield event.delta

    # ==================================================
    # AI 답변
    # ==================================================

    with st.chat_message("assistant"):

        response = st.write_stream(
            response_generator()
        )

    # ==================================================
    # AI 답변 저장
    # ==================================================

    st.session_state.messages.append(
        {
            "role": "assistant",
            "content": response
        }
    )
